def matrix_path(gait: str) -> Path:
    return stage_dir("derived", "combined") / f"combined_data_{gait}.npz"


def load_matrix(gait: str):
    path = matrix_path(gait)
    if not path.is_file():
        raise FileNotFoundError(
            f"Combined matrix not found for gait condition {gait!r}: {path}\n\n"
            "Build it with:\n"
            "    python pipeline/combine_reference_data.py matrices --config "
            f"config/measured_gait/{gait}.json\n\n"
            "Or download the published 03_derived stage, which contains it."
        )
    data = np.load(path, allow_pickle=True)
    convention = str(data["region_convention"]) if "region_convention" in data.files else "unknown"
    if convention != "anatomical":
        raise ValueError(
            f"{path.name} carries region_convention={convention!r}; the compartment "
            "split needs the anatomical labels. The axis-sign alternative mixes "
            "roughly a third of the trochlea into the femoral compartments."
        )
    return data


def compartment_summary(cum, peak, mean, contacted):
    """One compartment of one knee: cumulative, peak and mean pressure in MPa.

    The peak is the 95th percentile of the per-vertex maximum. A plain maximum
    is one vertex of twenty thousand and moves
    visibly between neighbouring simulations; the percentile describes the same
    highly-loaded patch without being a single point.
    """
    if contacted.sum() < MIN_CONTACT_VERTICES:
        return None
    return {
        "cum": float(np.mean(cum[contacted])) * 1e-6,
        "p95": float(np.percentile(peak[contacted], 95)) * 1e-6,
        "mean": float(np.mean(mean[contacted])) * 1e-6,
        "n_vertices": int(contacted.sum()),
    }


def compartment_pressure(gait, data, outlier_set, chronic):
    """Per-knee compartment pressure for one gait, plus what it excluded."""
    qc_tag = cohorts.QC_TAG[gait]
    knees = list(data["subjects"])
    groups = list(data["groups"])

    fields = {}
    for bone in BONES:
        fields[bone] = {
            "mask": data[f"{bone}_region_mask"],
            "has": data[f"{bone}_has_pressure"],
            **{short: data[f"{bone}_{key}"] for short, key in PRESSURE_SOURCE.items()},
        }

    rows, excluded = [], []
    for index, knee in enumerate(knees):
        if knee in chronic:
            excluded.append({"gait": gait, "knee": knee, "reason": "chronic knee"})
            continue
        if (qc_tag, knee) in outlier_set:
            excluded.append({"gait": gait, "knee": knee,
                             "reason": "flagged simulation (union policy)"})
            continue

        row = {"gait": gait, "knee": knee, "group": groups[index]}
        for bone, field in fields.items():
            has = field["has"][index]
            for code, short in REGION_NAME.items():
                summary = compartment_summary(
                    field["cum"][index], field["p95"][index], field["mean"][index],
                    (field["mask"] == code) & has,
                )
                for metric in PRESSURE_SOURCE:
                    row[f"{bone}_{short}_{metric}"] = (
                        summary[metric] if summary else float("nan"))
                row[f"{bone}_{short}_n_vertices"] = summary["n_vertices"] if summary else 0
            # Compartment balance as a fraction, med / (med + lat). The raw
            # medial-to-lateral ratio is unbounded and its spread explodes for
            # knees whose lateral compartment barely contacts; the fraction is
            # bounded in [0, 1] and stays well behaved there.
            #
            # Defined only when both compartments carry load. Two knees in this
            # cohort have identically zero lateral pressure across all ~7,000
            # lateral vertices on both bones -- their lateral compartment never
            # contacts during stance -- and for those the fraction has no
            # meaningful denominator. Admitting them as
            # 1.0 would put the two most extreme possible values into a
            # nine-point correlation.
            for metric in ("cum", "p95"):
                med, lat = row[f"{bone}_med_{metric}"], row[f"{bone}_lat_{metric}"]
                both_loaded = np.isfinite(med) and np.isfinite(lat) and med > 0 and lat > 0
                row[f"{bone}_medfrac_{metric}"] = (
                    med / (med + lat) if both_loaded else float("nan"))
        rows.append(row)

    n_chronic = sum(1 for e in excluded if e["reason"] == "chronic knee")
    print(f"  {gait:14s} in matrix {len(knees):4d}  "
          f"excluded {len(excluded) - n_chronic:2d} flagged + {n_chronic:2d} chronic  "
          f"analysed {len(rows):4d}", flush=True)
    return rows, excluded, len(knees)


# --------------------------------------------------------------------------- #
# The n = 9 statistic                                                         #
# --------------------------------------------------------------------------- #
def outcome_columns(cells) -> list[str]:
    """Every numeric pressure column, so nothing is summarised by omission."""
    skip = {"gait", "knee", "group"}
    return [key for key in cells[0]
            if key not in skip and not key.endswith("_n_vertices")
            and not key.startswith("kam_") and key != "body_mass"]


def gait_means(cells, gaits, covariate_summary) -> list[dict]:
    """One row per gait: the nine points every statistic in this figure uses.

    Both covariate estimators are written side by side. ``kam_peakN`` is the mean
    over the included simulations, which is what the scatter's centroids are and
    therefore what its correlation must be computed on. ``kam_peakN_cohort_median``
    is the median over every knee that produced inverse dynamics, which is what
    the per-vertex maps use. Carrying both in one table lets the two halves of
    the figure be checked against each other, which ``derivation_meta.json``
    does.
    """
    columns = outcome_columns(cells)
    rows = []
    for gait in gaits:
        members = [c for c in cells if c["gait"] == gait]
        row = {
            "gait": gait,
            "n_simulations": len(members),
            "body_mass": covariate_summary[gait]["body_mass"],
        }
        for key in ("kam_peak1", "kam_peak2"):
            values = np.array([c[key] for c in members], float)
            values = values[np.isfinite(values)]
            row[key] = float(values.mean()) if values.size else float("nan")
            row[f"{key}_cohort_median"] = covariate_summary[gait][key]
        for column in columns:
            values = np.array([c[column] for c in members], float)
            values = values[np.isfinite(values)]
            row[column] = float(values.mean()) if values.size else float("nan")
            row[f"{column}_sd"] = float(values.std()) if values.size else float("nan")
        rows.append(row)
    return rows


def correlations(gait_rows, columns) -> list[dict]:
    """Pearson r at n = 9 for every outcome × covariate."""
    from scipy.stats import pearsonr

    out = []
    for column in columns:
        y = np.array([row[column] for row in gait_rows], float)
        for covariate, _label in COVARIATES:
            x = np.array([row[covariate] for row in gait_rows], float)
            ok = np.isfinite(x) & np.isfinite(y)
            if ok.sum() < 3:
                continue
            r, p = pearsonr(x[ok], y[ok])
            out.append({"outcome": column, "covariate": covariate,
                        "r": float(r), "p_value": float(p), "n_gaits": int(ok.sum())})
    return out


# --------------------------------------------------------------------------- #
# The per-vertex maps                                                         #
# --------------------------------------------------------------------------- #
def gait_mean_pressure_maps(bone, gaits, included_by_gait):
    """``(means, valid)`` -- one mean pressure map per gait, and where it counts.

    The mean is over the knees that have pressure at a vertex, so a vertex
    outside one knee's contact patch does not pull the gait's
    mean toward zero. A vertex counts for a gait once enough of its knees reach
    it; the correlation then uses only vertices that count for all nine.
    """
    means, valid = [], []
    for gait in gaits:
        data = load_matrix(gait)
        knees = list(data["subjects"])
        keep = np.array([knee in included_by_gait[gait] for knee in knees], bool)

        pressure = data[f"{bone}_{MAP_PRESSURE}"][keep].astype(np.float64)
        has = data[f"{bone}_has_pressure"][keep]
        pressure = np.where(has, pressure, 0.0)

        n_with = has.sum(axis=0)
        with np.errstate(invalid="ignore", divide="ignore"):
            means.append(np.where(n_with > 0, pressure.sum(axis=0) / np.maximum(n_with, 1), 0.0))
        valid.append(n_with >= MAP_MIN_COVERAGE * keep.sum())
        del data
    return np.array(means), np.array(valid)


def vertex_correlation(maps, covariate, valid):
    """Per-vertex Pearson r between the nine gait-mean maps and nine values."""
    x = np.asarray(covariate, float)
    x = (x - x.mean()) / x.std()

    r = np.full(maps.shape[1], np.nan)
    usable = valid.all(axis=0)
    y = maps[:, usable]
    y = y - y.mean(axis=0, keepdims=True)
    sd = y.std(axis=0)
    varying = sd > 0

    correlated = np.full(y.shape[1], np.nan)
    correlated[varying] = (x[:, None] * (y[:, varying] / sd[varying])).mean(axis=0)
    r[usable] = correlated
    return r


def _render_panel(mesh, scalars, out_png: Path, view: str):
    """One bone rendered face-on, coloured by the correlation map."""
    import pyvista as pv

    pv.OFF_SCREEN = True
    pv.global_theme.background = "white"

    surface = mesh.copy()
    surface["r"] = scalars
    plotter = pv.Plotter(off_screen=True, window_size=MAP_WINDOW)
    plotter.add_mesh(surface, scalars="r", cmap=palette.DIVERGING_CMAP, clim=MAP_CLIM,
                     nan_color="lightgray", show_scalar_bar=False)

    bounds = mesh.bounds
    centre = [(bounds[0] + bounds[1]) / 2, (bounds[2] + bounds[3]) / 2,
              (bounds[4] + bounds[5]) / 2]
    span = max(bounds[1] - bounds[0], bounds[3] - bounds[2], bounds[5] - bounds[4])
    offset = 3 * span * (-1 if view == "inferior" else 1)
    # Viewing up the femur from below and down onto the tibia from above puts
    # both articular surfaces face-on; anterior (+y) up in both.
    plotter.camera_position = [
        (centre[0], centre[1], centre[2] + offset), tuple(centre), (0, 1, 0),
    ]
    plotter.camera.zoom(1.4)
    plotter.screenshot(str(out_png), transparent_background=False)
    plotter.close()


def _to_display_orientation(image, bone):
    """Medial right, lateral left, anterior top -- the same for both bones.

    The two cameras look at the knee from opposite sides, so the raw renders
    disagree about which side of the screen is medial. Reflecting them here
    lets a reader compare a femoral map with a tibial one directly.
    """
    return image[::-1, ::-1] if bone == "femur" else image[::-1, :]


def _autocrop(image, pad=6, white=250):
    """Trim the near-white margin so a panel fills its axes."""
    non_white = (image[..., :3] < white).any(axis=2)
    rows = np.where(non_white.any(axis=1))[0]
    columns = np.where(non_white.any(axis=0))[0]
    if not len(rows) or not len(columns):
        return image
    r0, r1 = max(rows[0] - pad, 0), min(rows[-1] + pad + 1, image.shape[0])
    c0, c1 = max(columns[0] - pad, 0), min(columns[-1] + pad + 1, image.shape[1])
    return image[r0:r1, c0:c1]


def _to_common_scale(panels, mediolateral_extent):
    """Put every panel on one physical scale and one canvas.

    Each render is framed against its own bounding box, so a femur and a tibia
    come back at different pixels per millimetre. Dropped into equal axes they
    would each stretch to fill their box and the tibia would be drawn as wide as
    the femur, although on a common scale the tibial plateau is about 8%
    wider than the femoral condyles and roughly a third shorter front to back.

    The screen horizontal is the mediolateral axis in both views, so pixels per
    millimetre is the panel width over that extent. Everything is resampled to
    the coarsest of those and padded onto one canvas, after which a single
    ``imshow`` scale applies to all six and the bones are drawn to scale.
    """
    from PIL import Image

    first = {}
    for (bone, _covariate), image in panels.items():
        first.setdefault(bone, image)
    per_unit = {bone: image.shape[1] / mediolateral_extent[bone]
                for bone, image in first.items()}
    target = min(per_unit.values())

    scaled = {}
    for key, image in panels.items():
        factor = target / per_unit[key[0]]
        if abs(factor - 1.0) > 1e-3:
            resized = Image.fromarray(image[..., :3]).resize(
                (max(1, round(image.shape[1] * factor)),
                 max(1, round(image.shape[0] * factor))),
                Image.LANCZOS,
            )
            image = np.asarray(resized)
        scaled[key] = image[..., :3]

    height = max(image.shape[0] for image in scaled.values())
    width = max(image.shape[1] for image in scaled.values())
    common = {}
    for key, image in scaled.items():
        canvas = np.full((height, width, 3), 255, np.uint8)
        top, left = (height - image.shape[0]) // 2, (width - image.shape[1]) // 2
        canvas[top:top + image.shape[0], left:left + image.shape[1]] = image
        common[key] = canvas
    return common


def build_maps(out_dir: Path, gaits, gait_rows, included_by_gait) -> dict:
    """Per-vertex correlation maps, written as arrays and as rendered panels."""
    import pyvista as pv
    from PIL import Image

    map_dir = out_dir / "maps"
    map_dir.mkdir(parents=True, exist_ok=True)

    panels, extent, coverage = {}, {}, {}
    for bone in BONES:
        surface = pv.read(reference_surface_path(bone))
        bounds = surface.bounds
        extent[bone] = bounds[1] - bounds[0]

        means, valid = gait_mean_pressure_maps(bone, gaits, included_by_gait)
        usable = int(valid.all(axis=0).sum())
        # Reaching all nine conditions is necessary but not sufficient: a vertex
        # whose nine gait means are identical has no variance to correlate. Both
        # counts are reported, because quoting the first as the analysed area
        # would roughly double it.
        coverage[bone] = {"n_vertices": int(means.shape[1]),
                          "n_vertices_reaching_all_gaits": usable,
                          "n_vertices_correlated": {}}
        print(f"  {bone:6s} {usable:6d} of {means.shape[1]} vertices reach all "
              f"{len(gaits)} conditions", flush=True)

        for covariate, _label in COVARIATES:
            values = [row[covariate if covariate == "body_mass"
                          else f"{covariate}_cohort_median"] for row in gait_rows]
            r = vertex_correlation(means, values, valid)
            coverage[bone]["n_vertices_correlated"][covariate] = int(np.isfinite(r).sum())
            np.save(map_dir / f"r_{bone}_{covariate}.npy", r)

            png = map_dir / f"{bone}__{covariate}.png"
            _render_panel(surface, r, png, MAP_VIEW[bone])
            panels[(bone, covariate)] = _autocrop(
                _to_display_orientation(np.asarray(Image.open(png)), bone))

    # Every panel is in memory before anything is written back, because the
    # common scale depends on all six at once. The raw render is then replaced
    # in place: what lands in 04_results is the panel as the figure draws it, so
    # a reader opening one of these PNGs sees the orientation the figure shows.
    for key, image in _to_common_scale(panels, extent).items():
        Image.fromarray(image).save(map_dir / f"{key[0]}__{key[1]}.png")
    for bone in BONES:
        correlated = coverage[bone]["n_vertices_correlated"]
        print(f"  {bone:6s} correlated at " + ", ".join(
            f"{n} vertices ({covariate})" for covariate, n in correlated.items()))
    print(f"  wrote {len(panels)} panels to {map_dir}")
    return coverage


