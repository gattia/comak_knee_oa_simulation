def derive(force=False, skip_maps=False, time_base="time") -> Path:
    if time_base not in TIME_BASES:
        raise SystemExit(f"--time-base must be one of {TIME_BASES}, not {time_base!r}")
    out_dir = stage_dir("results", FIGURE, create=True)
    cells_path = out_dir / "loading_cells.csv"
    if cells_path.exists() and not force:
        raise SystemExit(f"{cells_path} exists; --force to rebuild")

    conditions = gait_conditions()
    gaits = [gait for gait, _ in conditions]

    outlier_set = qc.load_outlier_set(
        source="union", cohort_tags=cohorts.resolve_qc_tags(qc.known_cohort_tags(), gaits))
    chronic = qc.load_chronic_knees()
    print(f"QC era {qc.ERA}, policy union, table {qc.unified_csv().name}")
    print(f"  {len(outlier_set)} flagged simulations, chronic knees {sorted(chronic)}\n")

    print(f"reading inverse dynamics for {len(gaits)} measured gait conditions "
          f"(KAM peaks split by {time_base})")
    kam_rows, covariate_summary = collect_covariates(conditions, time_base)
    kam_by_simulation = {(r["gait"], r["knee"]): r for r in kam_rows}
    write_csv(out_dir / "gait_covariates.csv", [covariate_summary[g] for g in gaits])

    print("\nsummarising compartment pressure")
    cells, excluded, ledger = [], [], []
    for gait in gaits:
        rows, dropped, n_in_matrix = compartment_pressure(
            gait, load_matrix(gait), outlier_set, chronic)
        missing_kam = 0
        for row in rows:
            peaks = kam_by_simulation.get((gait, row["knee"]))
            if peaks is None:
                missing_kam += 1
                dropped.append({"gait": gait, "knee": row["knee"],
                                "reason": "no inverse dynamics for this simulation"})
                continue
            row["kam_peak1"] = peaks["kam_peak1"]
            row["kam_peak2"] = peaks["kam_peak2"]
            row["body_mass"] = covariate_summary[gait]["body_mass"]
            cells.append(row)
        if missing_kam:
            print(f"  {gait:14s} {missing_kam} analysed knee(s) had no inverse dynamics")
        excluded.extend(dropped)
        n_chronic = sum(1 for e in dropped if e["reason"] == "chronic knee")
        ledger.append({
            "gait": gait,
            "n_knees_with_inverse_dynamics":
                covariate_summary[gait]["n_knees_with_inverse_dynamics"],
            "n_in_matrix": n_in_matrix,
            "n_excluded_flagged": len(dropped) - n_chronic - missing_kam,
            "n_excluded_chronic": n_chronic,
            "n_excluded_no_inverse_dynamics": missing_kam,
            "n_analysed": len(rows) - missing_kam,
        })

    if not cells:
        raise SystemExit("no simulations survived; check the combined matrices")

    # Column order: identity, covariates, then outcomes. The mixed model and the
    # figure both read by name, but a human opening this file should not have to
    # hunt for the three columns the analysis turns on.
    outcomes = outcome_columns(cells)
    order = (["gait", "knee", "group", "kam_peak1", "kam_peak2", "body_mass"]
             + outcomes + [k for k in cells[0] if k.endswith("_n_vertices")])
    write_csv(cells_path, cells, fieldnames=order)
    print(f"\nwrote {cells_path.name}: {len(cells):,} simulations, "
          f"{len({c['knee'] for c in cells})} knees, {len(gaits)} gait conditions")

    write_csv(out_dir / "gait_counts.csv", ledger)
    gait_rows = gait_means(cells, gaits, covariate_summary)
    write_csv(out_dir / "gait_means.csv", gait_rows)
    stats = correlations(gait_rows, outcomes)
    write_csv(out_dir / "gait_level_correlations.csv", stats)

    coverage = {}
    if skip_maps:
        # The panels on disk, if any, are from an earlier run and now describe a
        # different set of cells. Reported here, so a stale map is not drawn
        # beside fresh numbers unnoticed.
        print("\nskipping the per-vertex maps (--skip-maps); any maps/ panels on "
              "disk are from an earlier run and are NOT the ones these tables "
              "describe. Re-run without --skip-maps before rendering.")
    else:
        print(f"\nbuilding per-vertex correlation maps at n = {len(gaits)}")
        included_by_gait = {gait: {c["knee"] for c in cells if c["gait"] == gait}
                            for gait in gaits}
        coverage = build_maps(out_dir, gaits, gait_rows, included_by_gait)

    meta = write_meta(out_dir, cells, excluded, gait_rows, stats, chronic, coverage, gaits,
                      time_base)
    write_manifest(out_dir, cells, excluded, ledger, meta)

    headline = [s for s in stats if s["outcome"] == "tibia_med_cum"]
    print(f"\nThe manuscript's primary cell -- medial tibia cumulative pressure, n = {len(gaits)}:")
    for row in headline:
        print(f"  vs {row['covariate']:10s} r = {row['r']:+.3f}  p = {row['p_value']:.4f}")
    print(f"\nFigure 7 inputs in {out_dir}")
    print("Next: figures/figure6_loading_determinants.py "
          "(and figures/figure6_mundlak_model.R for the reported inference)")
    return out_dir


def write_meta(out_dir, cells, excluded, gait_rows, stats, chronic, coverage, gaits,
               time_base="time") -> dict:
    """The analysis choices and the population, for the figure to read back.

    ``covariate_estimator_agreement`` is the measured consequence of the figure's
    one internal inconsistency: the scatter correlates against the mean covariate
    over included simulations, the maps against the median over every knee that
    produced inverse dynamics. Recording the difference gives a reader a
    number to check.
    """
    from scipy.stats import pearsonr

    agreement = []
    for key in ("kam_peak1", "kam_peak2"):
        mean = np.array([row[key] for row in gait_rows], float)
        median = np.array([row[f"{key}_cohort_median"] for row in gait_rows], float)
        y = np.array([row["tibia_med_cum"] for row in gait_rows], float)
        agreement.append({
            "covariate": key,
            "max_abs_difference": float(np.abs(mean - median).max()),
            "r_using_simulation_mean": float(pearsonr(mean, y)[0]),
            "r_using_cohort_median": float(pearsonr(median, y)[0]),
        })

    # A column that is quietly NaN for some simulations means its gait mean is
    # over a different population than its neighbours', so the count is recorded.
    undefined = {
        column: int(sum(1 for c in cells if not np.isfinite(c[column])))
        for column in outcome_columns(cells)
        if any(not np.isfinite(c[column]) for c in cells)
    }

    n_chronic = sum(1 for e in excluded if e["reason"] == "chronic knee")
    meta = {
        "n_gaits": len(gaits),
        "unit_of_observation": "gait condition",
        "n_knees": len({c["knee"] for c in cells}),
        "n_simulations": len(cells),
        "gaits": list(gaits),
        "reference_gait_excluded": True,
        "reference_gait_reason":
            "the reference condition is a published overground trial with no gait "
            "donor, so it supplies no adduction moment and no body mass",
        "covariates": [key for key, _ in COVARIATES],
        "covariate_labels": {key: label for key, label in COVARIATES},
        "kam_time_base": time_base,
        "kam_peak_definition":
            "maximum external knee adduction moment over the first (peak 1) and "
            "second (peak 2) half of stance; 'time' splits at 50 % of the recorded "
            "stance window and drops frames outside it, 'frame' splits the "
            "inverse-dynamics file at len // 2 (v2). Peak 2 is a maximum, not "
            "necessarily a local peak",
        "primary_outcome": "tibia_med_cum",
        "map_pressure": MAP_PRESSURE,
        "map_min_coverage": MAP_MIN_COVERAGE,
        "map_clim": list(MAP_CLIM),
        # Empty when the run skipped the panels, so "which cells are these maps
        # of" is answerable from the metadata.
        "maps_rebuilt": bool(coverage),
        "map_coverage": coverage,
        "spm": False,
        "spm_note":
            "no cluster inference: testing each simulation as an independent "
            "observation would be pseudoreplication, and the test with the gait "
            "condition as the unit (n = 9) found no significant cluster. These maps "
            "are descriptive.",
        "qc_era": qc.ERA,
        "qc_policy": "union",
        "qc_table": qc.unified_csv().name,
        "n_excluded_flagged": len(excluded) - n_chronic,
        "n_excluded_chronic": n_chronic,
        "chronic_knees": sorted(chronic),
        "undefined_outcome_cells": undefined,
        "undefined_outcome_note":
            "the medial fraction is undefined where a compartment carried no load "
            "at all; those simulations are in loading_cells.csv with every other "
            "outcome intact, and only that column's gait mean omits them",
        "covariate_estimator_agreement": agreement,
        "headline": [s for s in stats if s["outcome"] == "tibia_med_cum"],
    }
    (out_dir / "derivation_meta.json").write_text(
        json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    return meta


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--skip-maps", action="store_true",
                        help="tables only; skip the six rendered correlation panels")
    parser.add_argument("--force", action="store_true",
                        help="rebuild even if the loading cells already exist")
    parser.add_argument("--time-base", choices=list(TIME_BASES), default="time",
                        help="split stance for the KAM peaks by time in the recorded "
                             "stance window (default), or by frame index as v2 did")
    args = parser.parse_args()
    derive(force=args.force, skip_maps=args.skip_maps, time_base=args.time_base)


if __name__ == "__main__":
    main()
