def gait_conditions() -> list[tuple[str, str]]:
    """``[(gait, results_dir template), ...]`` for the nine measured conditions.

    Read from the run configs, which produced the simulations and so describe
    where a condition's output lives. Ordered by ``cohorts.MEASURED``, which is
    also the figure's legend and colour order.
    """
    found = []
    for gait in cohorts.MEASURED:
        path = cohorts.condition_config_path(gait)
        if not path.is_file():
            raise FileNotFoundError(
                f"No run config for measured gait condition {gait!r}: {path}\n\n"
                "The nine conditions are declared by config/measured_gait/. A "
                "missing one would silently make this figure's reported n = 8."
            )
        # Through the config loader, which fills in the run's name ({run}); the
        # raw JSON value would name a directory that does not exist.
        found.append((gait, cohorts.condition_config(gait).get("run", "results_dir")))
    return found


def results_dir(template: str, knee: Knee) -> Path:
    """A condition's results directory for one knee, from its config template."""
    relative = knee.substitute(template)
    stage, rest = relative.split("/", 1)
    stage_name = {"02_simulations": "simulations", "01_models": "models"}[stage]
    return stage_dir(stage_name, *rest.split("/"))


def condition_knees(template: str, gait: str) -> list[Knee]:
    """Every knee directory a condition actually holds.

    Discovered from the condition's own tree, and asserted non-empty. A
    directory named ``OARSI_multigait_<gait>_bts_v2`` can exist beside these
    holding only worker logs, so a path built by formatting a cohort tag can
    resolve to something real, match zero knees, and finish cleanly over
    nothing. Downstream that looks like "this condition has fewer knees", which
    is why the count is checked.
    """
    if "{knee}" not in template:
        raise ValueError(
            f"run config for {gait!r} has results_dir {template!r}, which names no "
            "{knee}. This step enumerates a condition's knees from that level."
        )
    prefix = template.split("{knee}")[0].rstrip("/")
    stage, rest = prefix.split("/", 1)
    condition_root = stage_dir({"02_simulations": "simulations"}[stage], *rest.split("/"))
    if not condition_root.is_dir():
        raise FileNotFoundError(
            f"Gait condition {gait!r} has no simulation tree at {condition_root}.\n\n"
            "Download the published 02_simulations stage, or run:\n"
            f"    python pipeline/run_knee.py simulate --config "
            f"config/measured_gait/{gait}.json --knee <KNEE>"
        )
    knees = [Knee.parse(p.name) for p in sorted(condition_root.iterdir())
             if p.is_dir() and "_00m_" in p.name]
    if not knees:
        raise RuntimeError(
            f"Gait condition {gait!r} resolved to {condition_root} but holds zero "
            "knee directories -- refusing to run over an empty condition."
        )
    return knees


# --------------------------------------------------------------------------- #
# The covariates: knee adduction moment, and body mass                        #
# --------------------------------------------------------------------------- #
def read_sto_column(path: Path, column: str):
    """``(time, values)`` for one column of an OpenSim storage file, or None."""
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return None
    try:
        header_end = next(i for i, line in enumerate(lines) if line.strip() == "endheader")
    except StopIteration:
        return None
    names = lines[header_end + 1].strip().split("\t")
    if column not in names or "time" not in names:
        return None
    ci, ti = names.index(column), names.index("time")

    times, values = [], []
    for row in lines[header_end + 2:]:
        parts = row.strip().split("\t")
        if len(parts) <= max(ci, ti):
            continue
        try:
            times.append(float(parts[ti]))
            values.append(float(parts[ci]))
        except ValueError:
            continue
    if len(values) < 4:
        return None
    return np.asarray(times), np.asarray(values)


def kam_peaks(inverse_dynamics: Path, time_base: str = "time"):
    """Early- and late-stance knee adduction moment peaks, in N·m.

    The stored generalised force is the internal moment, so the external
    adduction moment -- the one the gait literature reports, positive for medial
    loading -- is its negation. The two peaks are the maxima over the first and
    second halves of stance.

    ``time_base`` (``TIME_BASES``) says where the halves split:

    * ``"time"`` -- at 50 % of the stance window the run recorded
      (``derive_figure2_data.stance_window``: ``run_record.json`` less its pad),
      by each frame's time; frames more than half a step outside stance are
      dropped. A padded run's inverse-dynamics file starts a frame before heel
      strike, so splitting it by index would move the split by half a frame.
    * ``"frame"`` -- at ``len // 2`` of the file, as in the v2 run, which treats
      the file as stance.

    "Peak 2" is the maximum over the second half, not necessarily a local
    peak: for donors whose adduction moment is still falling at mid-stance it is
    the value at the split.
    """
    if time_base not in TIME_BASES:
        raise ValueError(f"time_base must be one of {TIME_BASES}, not {time_base!r}")
    read = read_sto_column(inverse_dynamics, KAM_COLUMN)
    if read is None:
        return None
    times, kam = read[0], -read[1]
    if time_base == "frame":
        half = len(kam) // 2
        return float(np.nanmax(kam[:half])), float(np.nanmax(kam[half:]))
    # .../<results_dir>/comak-inverse-dynamics/inverse-dynamics.sto
    window = stance_window(inverse_dynamics.parent.parent)
    stance_percent(times, window, inverse_dynamics)  # raises if these frames are not this window's
    start, stop = window
    # A frame is in stance if it lies within half a frame step of the window: the
    # toe-off frame of an AddBiomechanics trial (stamped at 100.008 Hz) sits ~1e-4 s
    # past the recorded stop, while a padded run's extra first frame sits a whole
    # step before heel strike.
    tolerance = 0.5 * float(np.median(np.diff(times)))
    inside = (times >= start - tolerance) & (times <= stop + tolerance)
    mid = start + 0.5 * (stop - start)
    early, late = kam[inside & (times < mid)], kam[inside & (times >= mid)]
    if early.size == 0 or late.size == 0:
        raise ValueError(f"{inverse_dynamics}: no frames in one half of stance")
    return float(np.nanmax(early)), float(np.nanmax(late))


def donor_body_mass(condition_dir: Path):
    """The gait donor's total body mass, from this knee's scaling report.

    Every knee in a condition is scaled to the same donor's body, so this is a
    property of the condition. It is read per knee anyway and checked for
    constancy.
    """
    report = condition_dir.parent / "scaled_model" / "scaled_scaling_report.json"
    if not report.is_file():
        return None
    try:
        return float(json.loads(report.read_text(encoding="utf-8"))["subject_mass_kg"])
    except (ValueError, KeyError):
        return None


def collect_covariates(conditions, time_base: str = "time") -> tuple[list[dict], dict]:
    """Per-knee adduction moment and per-condition body mass, for all nine gaits.

    ``time_base`` is passed to ``kam_peaks``.

    Returns the per-simulation rows and ``{gait: summary}``. The summary's
    ``kam_peakN`` is the median over every knee that produced inverse dynamics --
    including knees quality control later excludes, because it describes the
    gait, not the analysed sample. The mean over the analysed sample is
    computed later, in ``gait_means``.
    """
    rows, summary = [], {}
    for gait, template in conditions:
        knees = condition_knees(template, gait)
        peaks1, peaks2, masses = [], [], set()
        for knee in knees:
            directory = results_dir(template, knee)
            peaks = kam_peaks(directory / "comak-inverse-dynamics" / "inverse-dynamics.sto",
                              time_base)
            if peaks is None:
                continue
            mass = donor_body_mass(directory)
            if mass is not None:
                masses.add(round(mass, 6))
            peaks1.append(peaks[0])
            peaks2.append(peaks[1])
            rows.append({"gait": gait, "knee": knee.name,
                         "kam_peak1": peaks[0], "kam_peak2": peaks[1]})

        if not peaks1:
            raise RuntimeError(
                f"Gait condition {gait!r}: none of its {len(knees)} knees yielded an "
                "inverse-dynamics.sto. The knees are there but the results "
                "subdirectory named by the run config is not."
            )
        if not masses:
            raise RuntimeError(
                f"Gait condition {gait!r}: no scaling report holds a donor body mass. "
                "It is the figure's third covariate; refusing to guess it."
            )
        if len(masses) > 1:
            raise RuntimeError(
                f"Gait condition {gait!r}: knees were scaled to {len(masses)} different "
                f"body masses ({sorted(masses)}). Body mass is a property of the gait "
                "donor and must be one value per condition."
            )

        summary[gait] = {
            "gait": gait,
            "qc_tag": cohorts.QC_TAG[gait],
            "n_knees_with_inverse_dynamics": len(peaks1),
            "body_mass": masses.pop(),
            "kam_peak1": float(np.median(peaks1)),
            "kam_peak2": float(np.median(peaks2)),
            "kam_peak1_sd": float(np.std(peaks1)),
            "kam_peak2_sd": float(np.std(peaks2)),
        }
        row = summary[gait]
        print(f"  {gait:14s} knees {row['n_knees_with_inverse_dynamics']:4d}  "
              f"mass {row['body_mass']:6.2f} kg  "
              f"KAM peak 1 {row['kam_peak1']:5.1f}  peak 2 {row['kam_peak2']:5.1f} N·m",
              flush=True)
    return rows, summary


