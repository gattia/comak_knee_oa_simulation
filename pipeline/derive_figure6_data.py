# The frontal-plane generalised force in the inverse-dynamics output. The
# detailed knee is always built as the model's right side whatever the knee's
# own side, so this column name is the same for every knee.
KAM_COLUMN = "knee_add_r_moment"

# Anatomical region codes as written by the region-label stage. The trochlea is
# patellofemoral cartilage and carries no tibiofemoral load, so it takes no part
# in a compartment-balance measure.
MEDIAL, LATERAL = 0, 1
REGION_NAME = {MEDIAL: "med", LATERAL: "lat"}

# A compartment needs this many contacting vertices to be summarised; fewer is
# a handful of triangles.
MIN_CONTACT_VERTICES = 5

# covariate key -> (column in gait_means used by the scatter, display label)
COVARIATES = [
    ("kam_peak1", "KAM peak 1 (N·m)"),
    ("kam_peak2", "KAM peak 2 (N·m)"),
    ("body_mass", "Body mass (kg)"),
]

# Outcomes carried per simulation. Pressures are converted to MPa; the cumulative
# one is a pressure-time integral over stance and keeps its own unit.
PRESSURE_SOURCE = {"cum": "pressure_cum", "p95": "pressure_max", "mean": "pressure_mean"}

# The per-vertex maps are built from cumulative pressure, matching the scatter's
# outcome. A vertex counts for a gait when at least this fraction of that gait's
# included knees have pressure there, and enters the correlation only when it
# counts for all nine -- an incomplete vertex would otherwise contribute a
# correlation over a different subset of gaits than its neighbours.
MAP_PRESSURE = "pressure_cum"
MAP_MIN_COVERAGE = 0.5

# Full correlation range. The maps reach ±0.9, so any percentile-based limit
# would truncate them and make a strong association look moderate.
MAP_CLIM = (-1.0, 1.0)
MAP_WINDOW = (700, 600)
# Camera per bone: the articular surface face-on, anterior toward the top.
MAP_VIEW = {"femur": "inferior", "tibia": "superior"}


