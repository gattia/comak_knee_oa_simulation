#!/usr/bin/env python3
"""Derive Figure 6's inputs: 02_simulations + 03_derived ->
04_results/figure6_loading_determinants.

Figure 6 asks what determines how hard a knee is loaded. The nine measured gait
conditions differ in their donor's knee adduction moment and body mass, and the
same ~740 knees are walked through all nine, so the question is answered by
varying the gait and holding the anatomy fixed -- the mirror image of Figure 3,
which holds the gait fixed and varies the anatomy.

The unit of observation is the gait, and n = 9
----------------------------------------------
Knee adduction moment and body mass are properties of the gait donor, not of the
OAI knee. All ~6,600 simulations carry only nine distinct loading conditions, so
correlating over simulations would test at df ≈ 6,570 on an effective n of nine
-- a design effect near 460. Every statistic here is therefore computed across
the nine gait means.

Aggregating to nine points costs almost nothing: each gait mean is pinned roughly
46 times more precisely than the gait means differ, and the same knees appear in
every condition, so it is effectively a paired design. The crossed mixed model in
``figures/figure6_mundlak_model.R`` confirms it from the other direction -- its
between-gait Mundlak term reproduces these p-values to three decimals.

The reference (overground) condition is absent because it has no gait donor and
therefore no covariate: it is a published reference trial, so the manuscript
describes this result as holding within the knee-osteoarthritis gait cohort.

There is no SPM here
--------------------
Spatial-parametric-mapping cluster inference over pooled simulations would test
nine distinct covariate values at df ≈ 6,500 (pseudoreplication), and at n = 9
it finds no significant cluster. The per-vertex maps this step computes are
descriptive -- a plain Pearson correlation at n = 9, no
permutation test, no threshold, nothing masked -- and the figure shows them on the
full −1..+1 scale below the panel that carries the statistic.

What it produces
----------------
``gait_covariates.csv``
    One row per gait condition: its knee-adduction-moment peaks and body mass,
    and how many knees each was measured over. The x-axis of the whole figure.
``loading_cells.csv``
    One row per simulation (gait × knee): that knee's own adduction-moment peaks
    under that gait, the gait's body mass, and its medial and lateral compartment
    pressure on both bones. The scatter's point cloud, and the mixed model's input.
``gait_means.csv``
    One row per gait: the mean over its included simulations of every covariate
    and every outcome. These nine points are the sample every statistic uses, and
    the large outlined dots the figure draws.
``gait_level_correlations.csv``
    Pearson r, p and n for every outcome × covariate at n = 9. The figure reads
    its annotations from here.
``gait_counts.csv``
    Per condition: knees with inverse dynamics, knees in the matrix, each
    exclusion count, and how many were analysed.
``maps/r_{bone}_{covariate}.npy`` and ``maps/{bone}__{covariate}.png``
    The per-vertex correlation between the nine gait-mean pressure maps and the
    nine covariate values, as data and as a rendered panel. The panels are
    rendered here, so redrawing the figure needs no 3D toolkit and no reference
    geometry.
``derivation_meta.json`` / ``inclusion_manifest.csv`` / ``inclusion_summary.md``
    The population, the exclusions and the analysis choices, generated by the
    pass that produced the numbers.

Two covariate estimators, one table
-----------------------------------
A gait's adduction moment can be summarised as the median over every knee that
produced inverse dynamics, or as the mean over the knees that survived quality
control and reached the statistic. The figure uses the first for the maps and
the second for the scatter, so both are carried, as two named columns of
``gait_means.csv``. The difference between them is recorded in
``derivation_meta.json``; on the headline outcome it moves r by under 0.001.

Quality control
---------------
Exclusions come from the shared table via ``figures/shared/qc.py`` and nowhere
else. Per-simulation union outliers drop that one solve; chronic knees -- flagged
under at least five conditions, which points to the reconstruction --
drop from every condition. Excluded simulations are not written to
``loading_cells.csv`` at all, so no consumer can use them by forgetting to
filter, and each one is named with its reason in the manifest.

Usage
-----
    python pipeline/derive_figure6_data.py
    python pipeline/derive_figure6_data.py --skip-maps --force
    python pipeline/derive_figure6_data.py --time-base frame   # the v2 run's KAM peak split
"""

