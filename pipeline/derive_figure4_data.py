import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "src"))
sys.path.insert(0, str(_REPO / "figures"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from comak_knee_oa import cohorts  # noqa: E402
from comak_knee_oa.paths import stage_dir  # noqa: E402
from derive_thickness import BONES, reference_surface_path  # noqa: E402
from shared import qc  # noqa: E402

FIGURE = "figure4_decile_dose_response"

N_BINS = 10
# A decile needs enough vertices for its mean to be a mean. Five per bin is the
# floor at which a cell is admitted at all; typical cells hold hundreds.
MIN_VERTICES_PER_BIN = 5

# Column in the combined matrix -> short name used throughout the analysis.
PRESSURE_METRICS = {"cum": "pressure_cum", "max": "pressure_max"}

# Anatomical region codes as written by the region-label stage.
REGION_CODES = {"medial": 0, "lateral": 1, "trochlea": 2}
# Condyles = medial and lateral together, trochlea excluded. This is the femoral
# surface that carries tibiofemoral load; "all" pools the trochlea in, which is
# patellofemoral cartilage and carries none of it.
CONDYLE_CODES = (0, 1)
REGIONS = {
    "femur": ("all", "condyles", "medial", "lateral", "trochlea"),
    "tibia": ("all", "condyles", "medial", "lateral"),
}

# Outcomes carried per cell. Signed: negative is thinning, positive thickening.
OUTCOMES = ("thinning_pct", "thinning_mm")


# --------------------------------------------------------------------------- #
# Inputs                                                                      #
# --------------------------------------------------------------------------- #
def matrix_path(gait: str) -> Path:
    return stage_dir("derived", "combined") / f"combined_data_{gait}.npz"


def load_matrix(gait: str):
    path = matrix_path(gait)
    if not path.is_file():
        config = ("config/reference_gait.json" if gait == cohorts.REFERENCE
                  else f"config/measured_gait/{gait}.json")
        raise FileNotFoundError(
            f"Combined matrix not found for gait condition {gait!r}: {path}\n\n"
            "Build it with:\n"
            f"    python pipeline/combine_reference_data.py matrices --config {config}\n\n"
            "Or download the published 03_derived stage, which contains it."
        )
    return np.load(path, allow_pickle=True)


def vertex_areas(bone: str) -> np.ndarray:
    """Per-vertex area of the reference cartilage surface.

    Each triangle gives a third of its area to each of its vertices, so the
    areas sum to the surface area and every vertex carries the share of surface
    it represents.
    """
    import pyvista as pv

    mesh = pv.read(reference_surface_path(bone))
    triangles = np.asarray(
        mesh.compute_cell_sizes(length=False, area=True, volume=False).cell_data["Area"]
    )
    faces = mesh.faces.reshape(-1, 4)[:, 1:]
    areas = np.zeros(mesh.n_points, dtype=np.float64)
    for corner in range(3):
        np.add.at(areas, faces[:, corner], triangles / 3.0)
    return areas


# --------------------------------------------------------------------------- #
# The cell                                                                    #
# --------------------------------------------------------------------------- #
def decile_cells(pressure, outcomes, baseline, area, valid, n_bins=N_BINS):
    """One (knee, gait, bone, region) -> its ``n_bins`` cells, or ``(None, n)``.

    Vertices with no pressure are not "low pressure": a vertex that never made
    contact has no rank on this scale, so it is excluded rather than filling the
    bottom decile with unloaded cartilage and flattening the dose-response.
    """
    selected = valid & (pressure > 0)
    n_valid = int(selected.sum())
    if n_valid < n_bins * MIN_VERTICES_PER_BIN:
        return None, n_valid

    p = pressure[selected]
    weight = area[selected]
    sampled = {name: matrix[selected] for name, matrix in outcomes.items()}
    base = baseline[selected]

    # Ordinal ranks, so ties break deterministically and every bin holds the
    # same number of vertices whatever the pressure distribution looks like.
    ranks = stats.rankdata(p, method="ordinal")
    binned = np.clip(np.ceil(ranks / len(ranks) * n_bins).astype(int), 1, n_bins)

    cells = []
    for b in range(1, n_bins + 1):
        member = binned == b
        w = weight[member]
        total = w.sum()
        if total <= 0:
            continue
        cell = {
            "decile": b,
            "mean_pressure": float(np.dot(w, p[member]) / total),
            "baseline_thickness": float(np.dot(w, base[member]) / total),
            "n_vertices": int(member.sum()),
        }
        cell.update(
            {name: float(np.dot(w, value[member]) / total) for name, value in sampled.items()}
        )
        cells.append(cell)
    return cells, n_valid


def region_selector(mask, region):
    if region == "all":
        return np.ones(mask.shape[0], dtype=bool)
    if region == "condyles":
        return np.isin(mask, CONDYLE_CODES)
    return mask == REGION_CODES[region]


def process_gait(gait, areas, outlier_set, chronic, n_bins=N_BINS):
    """Every cell for one gait condition, plus what it excluded.

    The condition has two names and neither is a function of the other: the
    matrix is filed under the gait donor, the quality-control rows under the
    pipeline run that produced them. ``cohorts.QC_TAG`` is the one place the map
    lives; formatting one name into the other resolves to a table that does not
    exist.
    """
    qc_tag = cohorts.QC_TAG[gait]
    data = load_matrix(gait)
    knees = list(data["subjects"])
    groups = list(data["groups"])

    convention = str(data["region_convention"]) if "region_convention" in data.files else "unknown"
    if convention != "anatomical":
        raise ValueError(
            f"{matrix_path(gait).name} carries region_convention={convention!r}; "
            "the regional analysis needs the anatomical labels. Rebuild the "
            "matrix with 'combine_reference_data.py matrices'."
        )

    excluded_sim = [k for k in knees if (qc_tag, k) in outlier_set and k not in chronic]
    excluded_chronic = [k for k in knees if k in chronic]
    dropped = set(excluded_sim) | set(excluded_chronic)

    rows = []
    contributed: dict[str, str] = {}
    for bone in BONES:
        mask = data[f"{bone}_region_mask"]
        area = areas[bone]
        has_pressure = data[f"{bone}_has_pressure"]
        has_thinning = data[f"{bone}_has_thinning"]
        baseline = data[f"{bone}_baseline_thickness"]
        outcome_matrices = {
            "thinning_mm": data[f"{bone}_thinning"],
            "thinning_pct": data[f"{bone}_thinning_pct"],
        }
        for metric, key in PRESSURE_METRICS.items():
            pressures = data[f"{bone}_{key}"]
            for region in REGIONS[bone]:
                selector = region_selector(mask, region)
                for index, knee in enumerate(knees):
                    if knee in dropped:
                        continue
                    valid = has_pressure[index] & has_thinning[index] & selector
                    cells, n_valid = decile_cells(
                        pressures[index],
                        {name: m[index] for name, m in outcome_matrices.items()},
                        baseline[index],
                        area,
                        valid,
                        n_bins,
                    )
                    if cells is None:
                        continue
                    for cell in cells:
                        rows.append(
                            {
                                "knee": knee,
                                "gait": gait,
                                "group": groups[index],
                                "bone": bone,
                                "region": region,
                                "pressure_metric": metric,
                                # decile_c in [-1, 1]: a single-degree-of-freedom
                                # trend whose slope reads directly as the change
                                # across the whole pressure range.
                                "decile_c": (cell["decile"] - 5.5) / 4.5,
                                "n_valid_vertices": n_valid,
                                **cell,
                            }
                        )
                    contributed[knee] = groups[index]

    print(
        f"  {gait:14s} in matrix {len(knees):4d}  "
        f"excluded {len(excluded_sim):2d} outlier + {len(excluded_chronic):2d} chronic  "
        f"analyzed {len(contributed):4d}  cells {len(rows):,}",
        flush=True,
    )
    return rows, {
        "gait": gait,
        "n_in_matrix": len(knees),
        "n_analyzed": len(contributed),
        "n_excluded_outlier": len(excluded_sim),
        "n_excluded_chronic": len(excluded_chronic),
        "excluded_outlier": sorted(excluded_sim),
        "excluded_chronic": sorted(excluded_chronic),
        "contributed": contributed,
    }


# --------------------------------------------------------------------------- #
# Summaries the figure reads                                                  #
# --------------------------------------------------------------------------- #
CELL_KEYS = ["bone", "region", "pressure_metric"]


def observed_means(cells: pd.DataFrame) -> pd.DataFrame:
    """Cell means collapsed over knees and gaits -- the figure's faint points."""
    summary = (
        cells.groupby(CELL_KEYS + ["group", "decile"], observed=True)[list(OUTCOMES)]
        .mean()
        .reset_index()
    )
    counts = (
        cells.groupby(CELL_KEYS + ["group", "decile"], observed=True)
        .size()
        .reset_index(name="n_cells")
    )
    return summary.merge(counts, on=CELL_KEYS + ["group", "decile"])


def within_knee_slopes(cells: pd.DataFrame, outcome: str) -> pd.DataFrame:
    """Per (gait, group): mean and SD across knees of the within-knee slope.

    The slope is ordinary least squares of the outcome on decile index, computed
    from group sums rather than by fitting each knee separately -- the same
    quantity, but 100,000 fits become five aggregations.
    """
    keys = CELL_KEYS + ["gait", "group", "knee"]
    frame = cells[keys + ["decile", outcome]].copy()
    frame["x"] = frame["decile"].astype(float)
    frame["y"] = frame[outcome].astype(float)
    frame["xy"] = frame["x"] * frame["y"]
    frame["xx"] = frame["x"] * frame["x"]

    grouped = frame.groupby(keys, observed=True).agg(
        n=("x", "size"), sx=("x", "sum"), sy=("y", "sum"), sxy=("xy", "sum"), sxx=("xx", "sum")
    )
    covariance = grouped["sxy"] - grouped["sx"] * grouped["sy"] / grouped["n"]
    variance = grouped["sxx"] - grouped["sx"] ** 2 / grouped["n"]
    # Fewer than three deciles, or no spread in decile index, is not a slope.
    slope = np.where((grouped["n"] >= 3) & (variance > 0), covariance / variance, np.nan)
    grouped = grouped.assign(slope=slope).reset_index()

    out = (
        grouped.groupby(CELL_KEYS + ["gait", "group"], observed=True)["slope"]
        .agg(["mean", "std", "count"])
        .reset_index()
        .rename(columns={"mean": "slope_mean", "std": "slope_sd", "count": "n_knees"})
    )
    out["outcome"] = outcome
    return out


# --------------------------------------------------------------------------- #
# Driver                                                                      #
# --------------------------------------------------------------------------- #
def derive(gaits=None, n_bins=N_BINS, force=False) -> Path:
    out_dir = stage_dir("results", FIGURE, create=True)
    cells_path = out_dir / "decile_cells.csv"
    if cells_path.exists() and not force:
        raise SystemExit(f"{cells_path} exists; --force to rebuild")

    gaits = list(gaits or cohorts.ALL)
    outlier_set = qc.load_outlier_set(source="union", cohort_tags=cohorts.qc_tags(gaits))
    chronic = qc.load_chronic_knees()
    print(f"QC era {qc.ERA}, policy union, table {qc.unified_csv().name}")
    print(f"  {len(outlier_set)} flagged simulations, chronic knees {sorted(chronic)}\n")

    areas = {}
    for bone in BONES:
        areas[bone] = vertex_areas(bone)
        area = areas[bone]
        print(
            f"reference {bone}: {len(area)} vertices, "
            f"mean area {area.mean():.3e} m², CV {area.std() / area.mean():.3f}"
        )
    print(f"\nprocessing {len(gaits)} gait conditions (deciles = {n_bins})")

    rows, ledger = [], []
    for gait in gaits:
        gait_rows, record = process_gait(gait, areas, outlier_set, chronic, n_bins)
        rows.extend(gait_rows)
        ledger.append(record)
    if not rows:
        raise SystemExit("no cells produced; check the combined matrices")

    cells = pd.DataFrame(rows)
    cells.to_csv(cells_path, index=False)
    print(f"\nwrote {cells_path.name}: {len(cells):,} cells")

    observed_means(cells).to_csv(out_dir / "observed_decile_means.csv", index=False)
    slopes = pd.concat([within_knee_slopes(cells, outcome) for outcome in OUTCOMES])
    slopes.to_csv(out_dir / "pergait_slopes.csv", index=False)

    write_population(out_dir, cells, ledger)
    write_manifest(out_dir, ledger, n_bins, cells)
    print(f"\nFigure 4 inputs in {out_dir}")
    print("Next: figures/figure4_decile_dose_response.R, then "
          "figures/figure4_decile_dose_response.py")
    return out_dir


def write_population(out_dir: Path, cells: pd.DataFrame, ledger: list[dict]) -> None:
    """Knees and simulations per group, and per gait condition."""
    per_group = (
        cells.groupby("group")
        .agg(n_knees=("knee", "nunique"), n_cells=("decile", "size"))
        .reset_index()
    )
    simulations = (
        cells[["gait", "knee", "group"]]
        .drop_duplicates()
        .groupby("group")
        .size()
        .rename("n_simulations")
    )
    per_group = per_group.merge(simulations, on="group").sort_values("group")
    per_group.to_csv(out_dir / "group_counts.csv", index=False)

    pd.DataFrame(
        [{k: v for k, v in record.items() if k not in ("contributed",)} for record in ledger]
    ).drop(columns=["excluded_outlier", "excluded_chronic"]).to_csv(
        out_dir / "gait_counts.csv", index=False
    )
    print("  group_counts.csv  " + "  ".join(
        f"{row.group}={row.n_knees}" for row in per_group.itertuples()))


def write_manifest(out_dir: Path, ledger: list[dict], n_bins: int, cells: pd.DataFrame) -> None:
    """The inclusion record, generated by the pass that produced the data.

    Written two ways: through the shared accessor, so this analysis
    appears alongside every other figure's manifest in ``04_results/inclusion``,
    and as a summary beside the figure's own inputs, so the exclusion counts a
    reader wants are in the directory they are already looking at.
    """
    included = [
        {"gait": record["gait"], "knee": knee, "group": group}
        for record in ledger
        for knee, group in sorted(record["contributed"].items())
    ]
    manifest = qc.write_inclusion_manifest(
        FIGURE, included, policy="union + chronic knees dropped entirely"
    )

    n_outlier = sum(r["n_excluded_outlier"] for r in ledger)
    n_chronic = sum(r["n_excluded_chronic"] for r in ledger)
    chronic_knees = sorted({k for r in ledger for k in r["excluded_chronic"]})
    meta = {
        "n_knees": int(cells["knee"].nunique()),
        "n_simulations": len(included),
        "n_gaits": len(ledger),
        "n_cells": int(len(cells)),
        "n_bins": n_bins,
        "outcomes": list(OUTCOMES),
        "regions": {bone: list(regions) for bone, regions in REGIONS.items()},
        "pressure_metrics": sorted(PRESSURE_METRICS),
        "qc_era": qc.ERA,
        "qc_policy": "union",
        "qc_table": qc.unified_csv().name,
        "n_excluded_outlier": n_outlier,
        "n_excluded_chronic": n_chronic,
        "chronic_knees": chronic_knees,
    }
    (out_dir / "derivation_meta.json").write_text(json.dumps(meta, indent=2) + "\n")

    lines = [
        "# Figure 4 -- inclusion",
        "",
        f"{meta['n_simulations']:,} simulations ({meta['n_knees']} knees x "
        f"{meta['n_gaits']} gait conditions) contributed "
        f"{meta['n_cells']:,} decile cells.",
        "",
        f"Quality control: era {qc.ERA}, union policy, from `{qc.unified_csv().name}`.",
        "",
        "| exclusion | simulations |",
        "|---|---:|",
        f"| flagged in either detector (per simulation) | {n_outlier} |",
        f"| chronic knee, dropped from every gait | {n_chronic} |",
        f"| **total** | **{n_outlier + n_chronic}** |",
        "",
        f"Chronic knees: {', '.join(chronic_knees) if chronic_knees else 'none'}.",
        "",
        "The chronic rule is not implied by the per-simulation one. A knee whose "
        "reconstruction is bad is flagged under most gaits but not necessarily "
        "all of them, and the per-simulation rule would keep it in the rest.",
        "",
        "| gait | in matrix | outlier | chronic | analyzed |",
        "|---|---:|---:|---:|---:|",
    ]
    lines += [
        f"| {r['gait']} | {r['n_in_matrix']} | {r['n_excluded_outlier']} | "
        f"{r['n_excluded_chronic']} | {r['n_analyzed']} |"
        for r in ledger
    ]
    (out_dir / "inclusion_summary.md").write_text("\n".join(lines) + "\n")
    print(f"  inclusion manifest: {manifest}")
    print(f"  {meta['n_knees']} knees, {meta['n_simulations']:,} simulations, "
          f"{n_outlier} outlier + {n_chronic} chronic excluded")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--gait", nargs="+", default=None, choices=list(cohorts.ALL),
                        help="gait conditions to process (default: all ten)")
    parser.add_argument("--n-bins", type=int, default=N_BINS,
                        help="pressure-rank bins per knee and gait")
    parser.add_argument("--force", action="store_true",
                        help="rebuild even if the cell table already exists")
    args = parser.parse_args()
    derive(gaits=args.gait, n_bins=args.n_bins, force=args.force)


if __name__ == "__main__":
    main()
