#!/usr/bin/env python3
"""Derive Figure 4's inputs: 03_derived -> 04_results/figure4_decile_dose_response.

Figure 4 asks whether cartilage thins faster where it is loaded harder, and
whether that dose-response differs between disease groups. This step turns the
per-vertex pressure and thinning matrices into the cell table the mixed model is
fitted on, plus the small summaries the figure draws.

The analysis cell
-----------------
One cell = (knee, gait, bone, region, pressure metric, decile). Its value is the
**area-weighted mean cartilage thickness change** of the vertices falling in that
within-knee, within-gait pressure-rank decile.

Three properties of that definition carry the analysis:

*Ranks, not magnitudes.* Deciles are equal-vertex-count bins of pressure rank
within one knee under one gait. A heavier person's knee is not shifted into the
top deciles by being heavier -- every knee spans deciles 1 to 10 by construction.
That is what makes the dose-response comparable across knees and across gait
conditions of very different absolute load.

*Area weighting, not vertex counting.* The reference surface's vertex areas have
a coefficient of variation near 0.18, so an unweighted mean would let mesh
density decide the cell value in the regions where resampling is least
uniform.

*Aggregating to cells, not modelling vertices.* Each vertex is used once per
(knee, gait). Cell means over roughly a two-thousandth of the surface are close
to Gaussian by the central limit theorem, and the worst of the pseudoreplication
-- twenty thousand correlated vertices per simulation -- is removed before the
model sees the data.

Thickness change is gait-invariant: the same per-vertex value is merely re-binned
under each gait's pressure ranking. The dose-response is therefore a statement
about *where* a gait puts load, not about how fast a gait wears cartilage.

What it produces
----------------
``decile_cells.csv``
    The long-form cell table, one row per cell. The mixed model's input, and the
    auditable record of what was analyzed. Left uncompressed:
    `data.table::fread` cannot read gzip without `R.utils`, which is not in
    `docs/r_environment.md`.
``observed_decile_means.csv``
    Cell means collapsed over knees and gaits, per (bone, region, metric, group,
    decile) -- the faint points the figure overlays on the fitted lines.
``pergait_slopes.csv``
    Per (gait, group) mean and SD across knees of the within-knee decile slope:
    the cross-gait consistency of the dose-response (data output).
``group_counts.csv`` / ``gait_counts.csv``
    Knees and simulations per disease group, and per gait condition with its
    exclusions. The figure's legend reads its n from ``group_counts.csv``, so
    anything the figure states about who is in it is generated here, by the same
    pass that produced the values.
``derivation_meta.json``
    Population, exclusion counts, and the analysis choices -- read back by the
    model and the figure rather than restated by either.
``inclusion_summary.md`` and ``04_results/inclusion/``
    Who survived quality control, generated by the code path the data came from.

Quality control
---------------
Exclusions come from the shared table via ``figures/shared/qc.py`` and from
nowhere else -- no per-script pressure threshold, no hardcoded knee list. Two
levels apply, and they are not redundant:

* per-simulation union outliers: this (gait, knee) solve produced a contact
  artifact, so that one simulation is dropped.
* chronic knees: flagged under at least five gaits, which is a bad
  reconstruction rather than a bad solve, so the knee is dropped from every gait.
  This removes a handful of simulations the per-simulation rule would have kept,
  in the gaits where a chronically bad knee happened not to trip a detector.

Usage
-----
    python pipeline/derive_figure4_data.py
    python pipeline/derive_figure4_data.py --gait default Subject_102 --force
"""

