#!/usr/bin/env python3
"""Derive Figure 3's inputs: 02_simulations -> 04_results/figure3_shape_pressure.

Figure 3 asks what happens to contact mechanics when only *shape* changes. A
healthy-to-mild-OA axis is fitted in the shape model's latent space, synthetic
knees are decoded at steps along it, and each is simulated under all nine
measured gaits. This step turns those simulations into the small tables the
figure reads.

What it produces
----------------
``waveforms_{bone}.npz``
    Medial and lateral compartment traces, resampled to 101 points of stance,
    stacked over the gaits that survived QC: ``{label}__{region}__{metric}`` ->
    ``(n_gaits, 101)``.
``shapes.json``
    The shape axis itself -- each label's sigma position, whether it is a step or
    a group anchor, in plot order.
``compartment_scalars.csv``
    One row per shape x gait x bone x region x peak, holding every metric read at
    the time of that compartment's mean-pressure peak (early stance for peak 1,
    late for peak 2). This is what the mixed model is fitted on. The metrics
    are sampled at a *common* time per peak rather than each taking its own
    maximum, so pressure and area describe the same instant and can be read
    together, which is what the figure compares.
``inclusion_manifest.csv`` / ``inclusion_summary.md``
    Every shape x gait x bone cell with its status and, when excluded, the
    reason, generated by the same code path as the tables above.

Compartment split
-----------------
Medial and lateral come from a local-z-sign split of the contact mesh, which
reproduces the solver's own region 4/5 definition. The mesh only exists
in world coordinates, so each simulation is localised through the forward
kinematics of its own model at frame 0 -- no registration, no cross-simulation
assumption. The split also yields a 95th-percentile pressure, which the solver's
per-region output does not provide and which the figure uses as its peak: the
plain maximum is a single triangle and is visibly noisy.

Replicates
----------
The tree is written by ``pipeline/run_synthetic.py``, one run per cell; all 90
converged on the first attempt, so there are no replicates. The fallback in
``extract_cell_with_replicates`` (to ``gait_{gait}_replicate_rNN`` runs beside
a missing canonical run) handles a tree in which some cells were re-attempted.

Quality control
---------------
The synthetic knees are not cohort knees, so the shared QC table has nothing to
key them on (see ``figures/shared/qc.py``). Two criteria are applied here, both
targeting the same artifact -- a contact patch that collapses to almost nothing,
making force per unit area explode:

1. medial mean pressure peaking above 15 MPa. Real medial mean pressure peaks
   around 5-7 MPa, so this is unambiguous.
2. medial contact area falling below 0.60 of its own mid-stance median. Criterion
   1 is calibrated on magnitude and misses the milder cases, which is why the
   artifact is also caught by its cause.

Both thresholds were calibrated on synthetic simulations that produced the
artifact. In the released tree neither comes close: over all 180 simulated
bones the medial mean-pressure peak is at most 6.0 MPa, and the area ratio has
median 0.885, p10 0.784 and minimum 0.762, so no cell is excluded or borderline.

Usage
-----
    python pipeline/derive_figure3_data.py
    python pipeline/derive_figure3_data.py --bone femur --force
    python pipeline/derive_figure3_data.py --time-base frame     # stance by frame index
"""

