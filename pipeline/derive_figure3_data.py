def sim_root() -> Path:
    return stage_dir("simulations", SIM_SUBDIR)


def gait_h5(label: str, gait: str) -> Path:
    return sim_root() / label / f"gait_{gait}" / "joint-mechanics" / "joint_mechanics.h5"


def replicate_h5s(label: str, gait: str) -> list[Path]:
    """Vendored replicate runs for a cell, in replicate order.

    A cell whose canonical simulation did not converge can be re-attempted (up
    to ten times); the attempts sit as ``gait_{gait}_replicate_rNN`` beside the
    canonical run.
    """
    pattern = f"gait_{gait}_replicate_r*/joint-mechanics/joint_mechanics.h5"
    return sorted((sim_root() / label).glob(pattern))


def _model_for_h5(h5_path: Path) -> Path | None:
    """The ``ik_constrained_model_final.osim`` beside a joint-mechanics file."""
    results_dir = h5_path.parent.parent
    direct = results_dir / "comak-inverse-kinematics" / "ik_constrained_model_final.osim"
    if direct.is_file():
        return direct
    found = sorted(results_dir.rglob("ik_constrained_model_final.osim"))
    return found[0] if found else None


