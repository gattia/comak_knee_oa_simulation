from derive_figure2_data import TIME_BASES, stance_percent, stance_window  # noqa: E402

FIGURE = "figure3_shape_pressure"
SIM_SUBDIR = "synthetic_shape_axis"

BONES = ("femur", "tibia")
MEDIAL, LATERAL = 0, 1
REGION_NAME = {MEDIAL: "medial", LATERAL: "lateral"}
N_GRID = 101

# The nine measured gait conditions the synthetic knees were walked through: the
# data root's donors. The ninth differs between data roots (RSubject_121 in v2,
# Subject_121 in v3), so the root decides rather than a config
# (config/synthetic_shape_axis.json names v3's donors, for running the arm). The
# reference (overground) condition is absent: Figure 3 is an ensemble over the
# measured gaits, and the reference differs from them in protocol, speed and
# population.
def measured_gaits() -> tuple[str, ...]:
    """The data root's measured donors, in its order."""
    return cohorts.measured()

# metric -> (dataset name in the aggregation, unit scale, label)
METRICS = {
    "mean_pressure": ("regional_mean_pressure", 1e-6, "Mean pressure (MPa)"),
    "p95_pressure": ("regional_p95_pressure", 1e-6, "Peak pressure · p95 (MPa)"),
    "max_pressure": ("regional_max_pressure", 1e-6, "Peak pressure · max (MPa)"),
    "contact_force": ("regional_contact_force", 1.0, "Contact force (N)"),
    "contact_area": ("regional_contact_area", 1e6, "Contact area (mm²)"),
}

OUTLIER_MEAN_P_MPA = 15.0
OUTLIER_AREA_COLLAPSE_FRAC = 0.60
_AREA_WINDOW = slice(20, 81)   # mid-stance; area legitimately reaches 0 at the ends

_TF_GROUP = "model/forceset/Smith2018ArticularContactForce/tf_contact/{cart}"
FRAME_BODY = {"femur": "femur_distal_r", "tibia": "tibia_proximal_r"}


