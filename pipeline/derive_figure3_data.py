def _frame0_coords(h5_path: Path) -> dict[str, float]:
    import h5py

    with h5py.File(h5_path, "r") as handle:
        coords = handle["model/coordinateset"]
        return {name: float(coords[f"{name}/value"][0]) for name in coords}


def _body_transform(model_path: Path, coord_values, body_name):
    """4x4 body-to-ground transform at the frame-0 pose.

    The stored coordinates come from a converged simulation and are fully
    defined, so the pose is set directly. ``assemble()`` is not called: it
    re-solves the coupled knee constraints and, when it cannot, relaxes them,
    returning a *different* pose than the one the simulation was in without an
    error. Rotational coordinates are stored in degrees.
    """
    import opensim as osim

    model = osim.Model(str(model_path))
    state = model.initSystem()
    coord_set = model.getCoordinateSet()
    for i in range(coord_set.getSize()):
        coord = coord_set.get(i)
        name = coord.getName()
        if name not in coord_values:
            continue
        value = float(coord_values[name])
        if coord.getMotionType() == 1:      # Rotational
            value = np.deg2rad(value)
        try:
            coord.setValue(state, value, False)
        except Exception:
            pass
    model.realizePosition(state)
    transform = model.getBodySet().get(body_name).getTransformInGround(state)
    rotation, position = transform.R(), transform.p()

    matrix = np.eye(4)
    for r in range(3):
        for c in range(3):
            matrix[r, c] = rotation.get(r, c)
        matrix[r, 3] = position.get(r)
    return matrix


def _contact_geometry(h5_dir: Path, bone: str):
    """Frame-0 contact surface -> (centroids, triangle areas, normals)."""
    import pyvista as pv

    candidates = sorted(
        h5_dir.glob(f"*contact_{bone}_cartilage*.vtp"),
        key=lambda p: int(p.stem.rsplit("_", 1)[-1]),
    )
    if not candidates:
        return None

    mesh = pv.read(str(candidates[0]))
    faces = mesh.faces.reshape(-1, 4)
    verts = mesh.points
    a, b, c = verts[faces[:, 1]], verts[faces[:, 2]], verts[faces[:, 3]]
    centroids = (a + b + c) / 3.0
    cross = np.cross(b - a, c - a)
    twice_area = np.linalg.norm(cross, axis=1)
    with np.errstate(invalid="ignore", divide="ignore"):
        normals = np.where(twice_area[:, None] > 0, cross / twice_area[:, None], 0.0)
    return centroids, 0.5 * twice_area, np.where(np.isfinite(normals), normals, 0.0)


def _triangle_regions(h5_path: Path, bone: str):
    """Per-triangle medial/lateral label, plus areas and normals."""
    geometry = _contact_geometry(h5_path.parent, bone)
    model_path = _model_for_h5(h5_path)
    if geometry is None or model_path is None:
        return None
    centroids, area, normal = geometry
    transform = _body_transform(model_path, _frame0_coords(h5_path), FRAME_BODY[bone])
    homogeneous = np.hstack([centroids, np.ones((len(centroids), 1))])
    local = (homogeneous @ np.linalg.inv(transform).T)[:, :3]
    # Negative local z is medial -- this reproduces the solver's region 4.
    region = np.where(local[:, 2] < 0.0, MEDIAL, LATERAL).astype(np.int16)
    return region, area, normal


def _aggregate(h5_path: Path, bone: str, region, area, normal):
    """Per-region traces, replicating the solver's own contact statistics.

    Mean pressure divides by the number of *contacting* triangles rather than by
    all of them, contact area sums only contacting triangles, and force is the
    norm of the vector sum of pressure x area x normal. Matching the solver here
    is what lets these numbers be compared with its per-region output.
    """
    import h5py

    group = _TF_GROUP.format(cart=f"{bone}_cartilage")
    with h5py.File(h5_path, "r") as handle:
        pressure = handle[f"{group}/triangle_pressure"][:]
        proximity = handle[f"{group}/triangle_proximity"][:]

    n_frames, n_tri = pressure.shape
    if n_tri != len(region):
        raise ValueError(f"{h5_path}: {n_tri} triangles, {len(region)} labels")

    out = {}
    for code in (MEDIAL, LATERAL):
        sel = region == code
        out[code] = {}
        if not sel.any():
            for metric in METRICS:
                out[code][metric] = np.zeros(n_frames)
            continue

        p = pressure[:, sel]
        contacting = proximity[:, sel] > 0.0
        n_contact = contacting.sum(axis=1)
        a = area[sel]
        n = normal[sel]

        with np.errstate(invalid="ignore", divide="ignore"):
            mean_p = p.sum(axis=1) / n_contact
        out[code]["mean_pressure"] = np.where(n_contact > 0, mean_p, 0.0)
        out[code]["max_pressure"] = np.abs(p).max(axis=1)

        import warnings
        masked = np.where(contacting, p, np.nan)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", category=RuntimeWarning)
            p95 = np.nanpercentile(masked, 95, axis=1)
        out[code]["p95_pressure"] = np.where(n_contact > 0, np.nan_to_num(p95), 0.0)

        out[code]["contact_area"] = (contacting * a[None, :]).sum(axis=1)
        out[code]["contact_force"] = np.linalg.norm((p * a[None, :]) @ n, axis=1)
    return out


def _resample(arr, n=N_GRID, percent=None):
    """``arr`` on the 0-100 % stance grid: by each frame's place in stance, or by index.

    As in Figure 2 (``derive_figure2_data._resample``): ``percent`` None places
    the first frame at 0 % and the last at 100 %; otherwise frames sit at their
    time in the recorded stance window, and
    the grid holds the first or last value where it runs past the kept frames.
    """
    arr = np.asarray(arr, dtype=np.float64).reshape(-1)
    if percent is None:
        if len(arr) == n:
            return arr
        return np.interp(np.linspace(0, 100, n), np.linspace(0, 100, len(arr)), arr)
    return np.interp(np.linspace(0, 100, n), percent, arr)


def _frame_percent(h5_path: Path) -> np.ndarray:
    """Each frame's position in its simulation's recorded stance window, in %."""
    import h5py

    with h5py.File(h5_path, "r") as handle:
        times = handle["time"][:]
    # .../gait_<donor>/joint-mechanics/joint_mechanics.h5: the cell's run directory
    return stance_percent(times, stance_window(h5_path.parent.parent), h5_path)


def extract_cell(h5_path: Path, bone: str, time_base: str = "time"):
    """One shape x gait x bone cell -> (traces, status, reason).

    ``traces`` is ``None`` whenever the cell is excluded, so a caller cannot
    accidentally use QC-failed data by ignoring the status. ``time_base`` is
    ``TIME_BASES``: "time" places frames by their time in stance, "frame" by
    index.
    """
    if not h5_path.is_file():
        return None, "missing", "no joint_mechanics.h5 (simulation did not complete)"
    # Outside the try below: a cell with no recorded stance window is a defect of
    # the run, not a per-cell "error".
    percent = _frame_percent(h5_path) if time_base == "time" else None

    try:
        labelled = _triangle_regions(h5_path, bone)
    except Exception as exc:                     # noqa: BLE001 - reported, not raised
        return None, "error", f"region split failed: {exc}"
    if labelled is None:
        return None, "error", "contact surface or model missing beside the h5"

    region, area, normal = labelled
    try:
        raw = _aggregate(h5_path, bone, region, area, normal)
    except Exception as exc:                     # noqa: BLE001
        return None, "error", f"aggregation failed: {exc}"

    traces = {
        code: {m: _resample(raw[code][m], percent=percent) * METRICS[m][1] for m in METRICS}
        for code in (MEDIAL, LATERAL)
    }

    medial = traces[MEDIAL]
    peak = float(np.nanmax(medial["mean_pressure"]))
    if np.isfinite(peak) and peak > OUTLIER_MEAN_P_MPA:
        return None, "excluded", (
            f"medial mean-pressure peak {peak:.0f} MPa "
            f"> {OUTLIER_MEAN_P_MPA:g} (contact-collapse artifact)"
        )

    window = medial["contact_area"][_AREA_WINDOW]
    median = float(np.nanmedian(window))
    if np.isfinite(median) and median > 0:
        frac = float(np.nanmin(window) / median)
        if frac < OUTLIER_AREA_COLLAPSE_FRAC:
            return None, "excluded", (
                f"mid-stance medial contact area collapses to {frac:.2f} of its "
                f"median < {OUTLIER_AREA_COLLAPSE_FRAC:g} "
                f"(peak pressure was only {peak:.1f} MPa)"
            )

    return traces, "included", ""


def extract_cell_with_replicates(label: str, gait: str, bone: str, time_base: str = "time"):
    """``extract_cell`` on the canonical run, falling back to replicates.

    Only when the canonical run produced no ``joint_mechanics.h5`` at all; a
    canonical result is never second-guessed. A QC-clean replicate carries the
    cell; when every replicate fails QC, the last one evaluated supplies the
    recorded statistics. Either way the reason names the replicate, so the
    manifest records that the cell's data is not from the canonical run.
    """
    traces, status, reason = extract_cell(gait_h5(label, gait), bone, time_base)
    if status != "missing":
        return traces, status, reason

    result = (traces, status, reason)
    for h5_path in replicate_h5s(label, gait):
        tag = h5_path.parent.parent.name
        traces, status, reason = extract_cell(h5_path, bone, time_base)
        if status == "included":
            return traces, status, f"from {tag} (canonical run did not converge)"
        if status != "missing":
            result = (traces, status, f"{reason} [{tag}]")
    return result


